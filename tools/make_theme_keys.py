"""Generates src/App/ChromeThemeKeys.h: every name WinUI's controls know
the theme brushes by.

The controls' resources in WinUI's generic.xaml are mostly aliases of a few
shared brushes ("ButtonForeground" is "TextFillColorPrimaryBrush").  A theme
has to replace each alias by name (see ChromeTheme.h), so this script follows
the aliases in the theme dictionaries of generic.xaml back to the brushes
listed in src/App/ChromeTheme.cpp.  Standard library only.

    python make_theme_keys.py [path\\to\\generic.xaml]

Run it again after updating the Windows App SDK.  Without an argument it
reads generic.xaml from the WinUI package under packages\\.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'src' / 'App' / 'ChromeTheme.cpp'
OUTPUT = ROOT / 'src' / 'App' / 'ChromeThemeKeys.h'
XAML_KEY = '{http://schemas.microsoft.com/winfx/2006/xaml}Key'
THEMES = {'Default': 'dark', 'Light': 'light'}
LINE = 100


def theme_dictionaries(path):
    root = ET.parse(path).getroot()
    for element in root.iter():
        if element.tag.endswith('ResourceDictionary.ThemeDictionaries'):
            found = {}
            for dictionary in element:
                name = dictionary.get(XAML_KEY)
                if name in THEMES:
                    found[name] = {e.get(XAML_KEY): e for e in dictionary if e.get(XAML_KEY)}
            return found
    raise SystemExit(f'{path}: no theme dictionaries')


def aliases(dictionary, brushes):
    """Maps each alias to the brush it ends at, for the brushes in `brushes`."""
    def target(key):
        seen = set()
        while key not in brushes and key not in seen:
            seen.add(key)
            element = dictionary.get(key)
            if element is None or not element.tag.endswith('StaticResource') or not element.get('ResourceKey'):
                return None
            key = element.get('ResourceKey')
        return key if key in brushes else None

    result = {}
    for key in dictionary:
        brush = target(key)
        if brush is not None and key != brush:
            result[key] = brush
    return result


def literal_lines(names, indent):
    lines, line = [], ''
    for name in names:
        if line and len(line) + 1 + len(name) > LINE:
            lines.append(line + ' ')
            line = name
        else:
            line = f'{line} {name}' if line else name
    lines.append(line)
    return [f'{indent}L"{text}"' for text in lines]


def main():
    if len(sys.argv) > 1:
        xaml = Path(sys.argv[1])
    else:
        candidates = sorted((ROOT / 'packages').glob('Microsoft.WindowsAppSDK.WinUI.*/lib/native/Microsoft.UI/Themes/generic.xaml'))
        if not candidates:
            raise SystemExit('No WinUI package under packages\\ (run build.ps1 once to restore it).')
        xaml = candidates[-1]
    package = next((p.name for p in xaml.parents if p.name.startswith('Microsoft.WindowsAppSDK.WinUI.')), xaml.name)

    brushes = re.findall(r'BrushSpec\{ L"(\w+)", Role::\w+(?:, [\d.]+)? \}', SOURCE.read_text(encoding='utf-8'))
    if not brushes:
        raise SystemExit(f'{SOURCE}: no BrushSpec table')
    dictionaries = theme_dictionaries(xaml)
    maps = {THEMES[name]: aliases(dictionaries[name], set(brushes)) for name in THEMES}
    for name in THEMES:
        missing = [b for b in brushes if b not in dictionaries[name]]
        if missing:
            raise SystemExit(f'{xaml}: {name} has no {", ".join(missing)}')

    out = [
        '// SpaceWindow - the names WinUI\'s controls know the theme brushes by.',
        '//',
        '// Generated by tools/make_theme_keys.py from the theme dictionaries in',
        f'// generic.xaml of {package}.  Do not edit; run the',
        '// script again after updating the Windows App SDK.',
        '#pragma once',
        '',
        '#include <string_view>',
        '',
        'namespace sm::ui',
        '{',
        '    struct BrushAliases',
        '    {',
        '        std::wstring_view brush;    // a brush in the table of ChromeTheme.cpp',
        '        bool dark;                  // the aliases are in the dark theme dictionary',
        '        bool light;                 // ... and in the light one',
        '        std::wstring_view aliases;  // separated by spaces',
        '    };',
        '',
        '    inline constexpr BrushAliases kBrushAliases[] = {',
    ]
    count = 0
    for brush in brushes:
        dark = sorted(k for k, b in maps['dark'].items() if b == brush)
        light = sorted(k for k, b in maps['light'].items() if b == brush)
        for names, in_dark, in_light in ((sorted(set(dark) & set(light)), True, True),
                                         (sorted(set(dark) - set(light)), True, False),
                                         (sorted(set(light) - set(dark)), False, True)):
            if not names:
                continue
            count += len(names)
            flags = f'{"true" if in_dark else "false"}, {"true" if in_light else "false"}'
            out.append(f'        {{ L"{brush}", {flags},')
            out.extend(literal_lines(names, '          '))
            out[-1] += ' },'
    out += ['    };', '}', '']
    OUTPUT.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{OUTPUT}: {count} aliases of {len(brushes)} brushes, from {xaml}')


if __name__ == '__main__':
    main()
